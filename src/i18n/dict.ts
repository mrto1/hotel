export function formatDay(day: string, locale: Locale): string {
  const d = new Date(day + "T12:00:00Z");
  return d.toLocaleDateString(locale === "de" ? "de-CH" : "en-GB", { weekday: "short", day: "numeric", month: "short", year: "numeric", timeZone: "UTC" });
}
